# -*- coding: utf-8 -*-
"""看板快照 → 仓库内文件（纯渲染器，2026-10-25）。

为什么有这个模块：**clone 一个仓库带不来看板**。交接**物**（AGENTS.md 那几个入口文件）
早就能写进仓库了，但"这块板现在什么状态"只有本机能看见 —— 接手方要么接 MCP、
要么等人把交接包粘一遍。把一份只读快照落到 `<仓库>/docs/kanban/` 之后两条路都通：
  · 人读 `README.md` 与每个项目一份 `<项目>.md`；
  · agent 读 `board.json` —— **不接 MCP 也能读**，这是它存在的意义。

四条纪律（写在这里，因为它们是这个模块的边界）：
  ① **数据仍以 `~/.ai-kanban` 为唯一真相源**：这里只渲染文本，不读盘、不写盘、不跑子进程；
     写不写盘由 `main.write_repo_snapshot()` 决定 —— 选项 A 的全部含义就在这一句里；
  ② **不认识脱敏**：脱敏由调用方在**渲染结果**上统一做。理由同约定 29（口径落在"实际给出去
     的那份文本"上）：渲染器自己盖一层，会让"预览显示原文、写盘写掩码"立刻分叉；
  ③ **每个文件都能自证来历**：正文第一行是 `MARKER_PREFIX`（`board.json` 走 `_snapshot` 字段），
     覆盖策略据此分辨"这是我们生成的（可更新）"与"用户手写的（默认不动）"；
  ④ **时间与版本都由调用方注入**：`render()` 不收时钟、不读版本号 ——
     用例不能依赖墙钟（测试约定 ③），且版本号只有 `app/version.py` 一处事实来源。
"""
from __future__ import annotations

import json
import re

SNAPSHOT_DIR = "docs/kanban"          # 相对仓库根；**只在这里定义**（钉子钉着不许抄第二处）
MARKER_PREFIX = "<!-- generated by ai-handoff-kanban"
JSON_MARKER_KEY = "_snapshot"

_NAME_BAD = re.compile(r'[\\/:*?"<>|\x00-\x1f]')
_WS = re.compile(r"\s+")
MAX_SLUG = 60


def marker_line(version: str, generated_at: str) -> str:
    """每个 Markdown 文件的第一行：既标明来历，也把"会被覆盖"说在前面。"""
    return (f"{MARKER_PREFIX} v{version} at {generated_at} —— "
            "这是看板导出快照：手工改动会在下次导出时被覆盖，改数据请用应用本身。 -->")


def is_ours(text: str) -> bool:
    """这份文件是不是我们生成的。

    Markdown 看第一行标记；JSON 看顶层 `_snapshot` 字段（JSON 不能有注释，
    所以两条路各认各的，但**判据只有这一处** —— 覆盖策略与用例都调它）。
    解析失败按"不是我们的"处理：宁可少覆盖一次，也不要把用户手写的文件冲掉。
    """
    if not text:
        return False
    if text.lstrip()[:len(MARKER_PREFIX)] == MARKER_PREFIX:
        return True
    head = text.lstrip()[:1]
    if head in "{[":
        try:
            doc = json.loads(text)
        except Exception:                                  # noqa: BLE001
            return False
        return isinstance(doc, dict) and bool(doc.get(JSON_MARKER_KEY))
    return False


def slugify(name: str, fallback: str) -> str:
    """项目名 → 文件名（中文保留；路径敌意字符换 `-`；空名字退回 id）。"""
    s = _NAME_BAD.sub("-", (name or "").strip())
    s = _WS.sub("-", s).strip(". -")
    return s[:MAX_SLUG] or fallback


def _due_and_flags(t: dict) -> str:
    bits = []
    if t.get("agent"):
        bits.append(f"@{t['agent']}")
    if t.get("due_date"):
        bits.append(f"截止 {t['due_date']}")
    if t.get("status") == "阻塞" and t.get("blocked_reason"):
        bits.append(f"阻塞：{t['blocked_reason']}")
    if t.get("milestone"):
        bits.append(f"节点 {t['milestone']}")
    return ("（" + "，".join(bits) + "）") if bits else ""


def _project_md(p: dict, mems: list[dict], *, marker: str) -> str:
    """一个项目的快照：交接要看的那几段 + 按状态分组的任务 + 未过期记忆。"""
    out = [marker, "", f"# {p.get('name') or p.get('id')}", ""]
    head = [f"状态 {p.get('status') or '—'}", f"优先级 {p.get('priority') or '—'}",
            f"进度 {p.get('progress', 0)}%"]
    out.append("· " + " · ".join(head))
    if p.get("repo_path"):
        out.append(f"· 仓库 `{p['repo_path']}`")
    if p.get("next_action"):
        out.append(f"· **下一步**：{p['next_action']}")
    if p.get("tags"):
        out.append("· 标签 " + "、".join(str(x) for x in p["tags"]))
    out.append("")

    for title, key in (("背景", "background"), ("交接说明", "handoff_note")):
        val = (p.get(key) or "").strip()
        if val:
            out += [f"## {title}", "", val, ""]

    tasks = p.get("tasks") or []
    order = ["进行中", "待办", "阻塞", "待审查", "已完成"]
    counts = {s: sum(1 for t in tasks if t.get("status") == s) for s in order}
    out += ["## 任务", "",
            "（" + " / ".join(f"{s} {counts[s]}" for s in order) + "）", ""]
    for status in order:
        group = [t for t in tasks if t.get("status") == status]
        if not group:
            continue
        out.append(f"### {status}")
        for t in group:
            out.append(f"- {t.get('title') or t.get('id')}{_due_and_flags(t)}")
            desc = (t.get("desc") or "").strip()
            if desc:
                out.append(f"  - {desc}")
            # 验收清单：已完成的不带（它已经验过了 —— 与约定 24 的其余落点同口径）
            if status != "已完成":
                for item in (t.get("acceptance") or []):
                    out.append(f"  - ☐ {item}")
            if t.get("journal"):
                out.append(f"  - 过程记录 {len(t['journal'])} 条（原样在应用里看）")
        out.append("")

    if mems:
        out += ["## 活跃记忆", ""]
        for m in mems:
            line = f"- [{m.get('type') or '事实'}] {m.get('text') or ''}"
            if m.get("expires"):
                line += f"（到期 {m['expires']}）"
            out.append(line)
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def _index_md(projects: list[dict], *, marker: str, generated_at: str) -> str:
    """`docs/kanban/` 的目录页：这是"看板在仓库里"对**人**的入口。"""
    out = [marker, "", "# 看板快照", "",
           f"导出时间 {generated_at}。这是**只读快照**（数据在应用自己的数据目录里，",
           "这里只是投影）；每行的「文件」是该项目的详情，agent 可直接读 `board.json`。", "",
           "| 项目 | 状态 | 优先级 | 进度 | 进行中 | 待办 | 文件 |",
           "| --- | --- | --- | ---: | ---: | ---: | --- |"]
    for p in projects:
        tasks = p.get("tasks") or []
        doing = sum(1 for t in tasks if t.get("status") == "进行中")
        todo = sum(1 for t in tasks if t.get("status") == "待办")
        fn = f"{slugify(p.get('name') or '', p.get('id') or 'project')}.md"
        out.append(f"| {p.get('name') or p.get('id')} | {p.get('status') or '—'} | "
                   f"{p.get('priority') or '—'} | {p.get('progress', 0)}% | {doing} | {todo} | "
                   f"[{fn}]({fn}) |")
    out.append("")
    return "\n".join(out) + "\n"


def _board_json(projects: list[dict], mems_by_pid: dict, *,
                version: str, generated_at: str) -> str:
    """机读的那一份：**不接 MCP 的 agent 靠它读看板**。字段与 HTTP/MCP 同口径，不另起一套。"""
    doc = {
        JSON_MARKER_KEY: {"generated_by": "ai-handoff-kanban", "version": version,
                          "generated_at": generated_at, "readonly": True},
        "projects": [{
            "id": p.get("id"), "name": p.get("name"), "status": p.get("status"),
            "priority": p.get("priority"), "progress": p.get("progress", 0),
            "next_action": p.get("next_action") or "", "repo_path": p.get("repo_path") or "",
            # 交接说明与背景也带上：**不接 MCP 的 agent 读的就是这份** ——
            # 少了这两段，它拿到的是"有哪些任务"，而不是"这项目为什么这样做"
            "background": p.get("background") or "",
            "handoff_note": p.get("handoff_note") or "",
            "tags": list(p.get("tags") or []),
            "tasks": [{
                "id": t.get("id"), "title": t.get("title"), "status": t.get("status"),
                "priority": t.get("priority"), "agent": t.get("agent") or "",
                "due_date": t.get("due_date") or "", "blocked_reason": t.get("blocked_reason") or "",
                "acceptance": list(t.get("acceptance") or []) if t.get("status") != "已完成" else [],
                "depends_on": list(t.get("depends_on") or []),
            } for t in (p.get("tasks") or [])],
            "memories": [{"type": m.get("type"), "text": m.get("text"),
                          "expires": m.get("expires") or ""} for m in mems_by_pid.get(p.get("id"), [])],
        } for p in projects],
    }
    return json.dumps(doc, ensure_ascii=False, indent=2) + "\n"


def render(projects: list[dict], memories: list[dict], *, version: str,
           generated_at: str) -> dict[str, str]:
    """→ `{相对仓库根的路径: 文本}`。**不含脱敏**（调用方在结果上统一做，见模块 docstring ②）。

    文件名冲突会各带 `-2`/`-3` 后缀：项目名重复在两个不同项目上很常见
    （"前端"改版、"前端"重构），同一个文件名互相覆盖等于**导出即丢一份**。
    """
    marker = marker_line(version, generated_at)
    by_pid: dict = {}
    for m in memories or []:
        by_pid.setdefault(m.get("pid"), []).append(m)

    files: dict[str, str] = {f"{SNAPSHOT_DIR}/README.md": _index_md(
        projects, marker=marker, generated_at=generated_at)}
    used: dict[str, int] = {}
    for p in projects:
        base = slugify(p.get("name") or "", p.get("id") or "project")
        n = used.get(base, 0) + 1
        used[base] = n
        fn = f"{base}.md" if n == 1 else f"{base}-{n}.md"
        mems = [m for m in by_pid.get(p.get("id"), []) if m.get("type") and m.get("text")]
        files[f"{SNAPSHOT_DIR}/{fn}"] = _project_md(p, mems, marker=marker)
    files[f"{SNAPSHOT_DIR}/board.json"] = _board_json(
        projects, by_pid, version=version, generated_at=generated_at)
    return files